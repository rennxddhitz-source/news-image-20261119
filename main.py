def draw_text2(x, y, text, color):
    cx = x
    for ch in text:
        if ch == '\\n':
            return cx
        if ch in FONT:
            bits = FONT[ch]
            for row in range(FH):
                for col in range(FW):
                    bit = (bits >> ((FH-1-row)*FW + col)) & 1
                    if bit:
                        for dy in range(SCALE):
                            for dx in range(SCALE):
                                setpx(cx + col*SCALE + dx, y + row*SCALE + dy, color)
        cx += (FW + 1) * SCALE
    return cx

