pixels = bytearray(W * H * 3)
def setpx(px, py, color):
    if 0 <= px < W and 0 <= py < H:
        i = (py * W + px) * 3
        pixels[i:i+3] = color

def fill_rect(x0, y0, x1, y1, color):
    for y in range(y0, y1):
        base = (y * W + x0) * 3
        for x in range(x0, x1):
            i = base + (x - x0) * 3
            pixels[i:i+3] = color

bg = (20, 30, 60); fg = (255, 255, 255); acc = (255, 200, 80)
